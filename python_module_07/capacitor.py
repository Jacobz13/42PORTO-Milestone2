from typing import cast
from ex1 import HealCapability, TransformCapability
from ex1 import HealingCreatureFactory, TransformCreatureFactory

heal_fact = HealingCreatureFactory()
h_base = heal_fact.create_base()
h_evolved = heal_fact.create_evolved()
trans_factory = TransformCreatureFactory()
t_base = trans_factory.create_base()
t_evolved = trans_factory.create_evolved()
print("Testing Creature with healing capability")
print(" base:")
print(h_base.describe())
print(h_base.attack())
print(cast(HealCapability, h_base).heal())
print(" evolved:")
print(h_evolved.describe())
print(h_evolved.attack())
print(cast(HealCapability, h_evolved).heal())
print("")
print("Testing Creature with transform capability\n base:")
print(t_base.describe())
print(t_base.attack())
print(cast(TransformCapability, t_base).transform())
print(t_base.attack())
print(cast(TransformCapability, t_base).revert())
print(" evolved:")
print(t_evolved.describe())
print(t_evolved.attack())
print(cast(TransformCapability, t_evolved).transform())
print(t_evolved.attack())
print(cast(TransformCapability, t_evolved).revert())
